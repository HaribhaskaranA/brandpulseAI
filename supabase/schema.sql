-- Enable pgvector extension for guideline RAG embedding vectors
create extension if not exists vector;

-- 1. Brand Guidelines Kit Table
create table if not exists public.brand_guidelines (
    id text primary key,
    name text not null,
    version text not null,
    approved_colors jsonb default '[]'::jsonb,
    tone_profile jsonb default '{}'::jsonb,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Brand Vault Rules Table (RAG Grounding & Policy Truth)
create table if not exists public.brand_rules (
    id text primary key,
    category text not null,
    title text not null,
    citation text not null,
    guideline_text text not null,
    verified_fact text,
    banned_terms text[],
    severity text default 'warning',
    active boolean default true,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. Anonymized Audit Telemetry (Zero-Knowledge, No Draft Body Copy Stored)
create table if not exists public.compliance_audits (
    id bigint generated by default as identity primary key,
    overall_score integer not null,
    categories_summary jsonb,
    violations_count integer default 0,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable Row Level Security (RLS)
alter table public.brand_guidelines enable row level security;
alter table public.brand_rules enable row level security;
alter table public.compliance_audits enable row level security;

-- Public Read & Write Policies for Anon Key (Hackathon Demo)
create policy "Allow public read access on brand_guidelines"
    on public.brand_guidelines for select
    using (true);

create policy "Allow public read access on brand_rules"
    on public.brand_rules for select
    using (true);

create policy "Allow public insert on compliance_audits"
    on public.compliance_audits for insert
    with check (true);

create policy "Allow public select on compliance_audits"
    on public.compliance_audits for select
    using (true);
