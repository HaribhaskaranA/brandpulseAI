const { Client } = require('pg');
require('dotenv').config();

const connectionString = process.env.DATABASE_URL || 'postgresql://postgres@aws-0-ap-southeast-1.pooler.supabase.com:5432/postgres';

const client = new Client({
  connectionString: process.env.DATABASE_URL ? process.env.DATABASE_URL.replace('db.vxruhsoxwfsbwtnxktvm.supabase.co:5432', 'aws-0-ap-southeast-1.pooler.supabase.com:5432') : undefined,
  ssl: { rejectUnauthorized: false }
});

async function run() {
  console.log('Connecting to Supabase PostgreSQL...');
  await client.connect();
  console.log('Connected!');

  const ddl = `
    create extension if not exists vector;

    create table if not exists public.posts (
      id text primary key,
      title text not null,
      channel text default 'Social Post',
      author text default 'Content Creator',
      content text,
      banner_url text,
      banner_name text,
      has_image boolean default false,
      has_contrast_issue boolean default false,
      status text default 'Private Draft',
      visibility text default 'private',
      last_audit jsonb,
      comments jsonb default '[]'::jsonb,
      history jsonb default '[]'::jsonb,
      created_at timestamp with time zone default timezone('utc'::text, now()) not null,
      updated_at timestamp with time zone default timezone('utc'::text, now()) not null
    );

    create table if not exists public.brand_guidelines (
      id text primary key,
      name text not null,
      version text not null,
      approved_colors jsonb default '[]'::jsonb,
      tone_profile jsonb default '{}'::jsonb,
      created_at timestamp with time zone default timezone('utc'::text, now()) not null
    );

    create table if not exists public.brand_rules (
      id text primary key,
      category text not null,
      title text not null,
      citation text not null,
      guideline_text text not null,
      verified_fact text,
      banned_terms text[],
      severity text default 'warning',
      active boolean default true,
      created_at timestamp with time zone default timezone('utc'::text, now()) not null
    );

    create table if not exists public.compliance_audits (
      id bigint generated by default as identity primary key,
      post_id text,
      overall_score integer not null,
      categories_summary jsonb,
      violations_count integer default 0,
      created_at timestamp with time zone default timezone('utc'::text, now()) not null
    );

    alter table public.posts enable row level security;
    alter table public.brand_guidelines enable row level security;
    alter table public.brand_rules enable row level security;
    alter table public.compliance_audits enable row level security;

    drop policy if exists "anon_posts_all" on public.posts;
    drop policy if exists "anon_guidelines_all" on public.brand_guidelines;
    drop policy if exists "anon_rules_all" on public.brand_rules;
    drop policy if exists "anon_audits_all" on public.compliance_audits;

    create policy "anon_posts_all" on public.posts for all using (true) with check (true);
    create policy "anon_guidelines_all" on public.brand_guidelines for all using (true) with check (true);
    create policy "anon_rules_all" on public.brand_rules for all using (true) with check (true);
    create policy "anon_audits_all" on public.compliance_audits for all using (true) with check (true);

    grant all on public.posts to anon, authenticated, service_role;
    grant all on public.brand_guidelines to anon, authenticated, service_role;
    grant all on public.brand_rules to anon, authenticated, service_role;
    grant all on public.compliance_audits to anon, authenticated, service_role;
    grant usage, select on all sequences in schema public to anon, authenticated, service_role;
  `;

  await client.query(ddl);
  console.log('Schema created successfully!');
  await client.end();
}

run().catch(err => {
  console.error('Error running setup:', err);
  process.exit(1);
});
